<?php

namespace App\Http\Controllers;

use App\Helpers\FileHelper;
use App\Models\File;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\BinaryFileResponse;

class FileController extends Controller
{
    /**
     * @param \Illuminate\Http\Request $request
     * @param integer $id
     *
     * @return BinaryFileResponse
     */
    public function show(Request $request, $id)
    {
        $file = File::findOrFail($id);

        // Stop the browser from sniffing a different, active type out of the content.
        $headers = ['X-Content-Type-Options' => 'nosniff'];

        if ($request->boolean('thumbnail')) {
            // Thumbnails are JPEGs generated by the server.
            return response()->file(storage_path('app/' . $file->thumbnail), $headers);
        }

        // Files stored before the type allow-list (e.g. SVG or HTML) could run scripts in the
        // app's origin: download them instead of rendering them, and sandbox them if opened anyway.
        if (!FileHelper::isAllowedMimeType($file->content_type)) {
            $headers['Content-Disposition'] = 'attachment';
            $headers['Content-Security-Policy'] = "default-src 'none'; sandbox";
        }

        return response()->file(storage_path('app/' . $file->path), $headers);
    }

    /**
     * @param Request $request
     *
     * @return array
     */
    public function uploadFile(Request $request)
    {
        if ($request->hasFile('file')) {
            if ($request->file('file')->isValid()) {
                $file = FileHelper::createFile($request->file('file'), File::FILE);

                return ['success' => true, 'message' => 'success_message.file_upload', 'data' => $file];
            }
        }

        return ['success' => false, 'message' => 'error_message.file_upload'];
    }
}
